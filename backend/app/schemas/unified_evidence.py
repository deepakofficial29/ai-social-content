"""Phase 3 — Unified evidence data model.

Every claim in this model is traceable to its source.
Observations, interpretations, and inferences are kept in separate fields.
Confidence is only populated when the provider supplies it or it is
meaningfully calibrated — never invented.

Schema version: 1
"""

from __future__ import annotations

import uuid
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional

from pydantic import BaseModel, Field


SCHEMA_VERSION = "1"


# ---------------------------------------------------------------------------
# Enumerations
# ---------------------------------------------------------------------------


class SourceModality(str, Enum):
    IMAGE = "image"
    VIDEO_FRAME = "video_frame"
    VIDEO_OVERALL = "video_overall"
    AUDIO_TRANSCRIPTION = "audio_transcription"
    AUDIO_UNDERSTANDING = "audio_understanding"
    OCR = "ocr"
    FUSION = "fusion"          # derived by combining multiple modalities
    SYSTEM = "system"          # generated by the pipeline itself


class EvidenceCategory(str, Enum):
    OBJECT = "object"
    PERSON = "person"
    ACTIVITY = "activity"
    SCENE = "scene"
    ENVIRONMENT = "environment"
    VISUAL_ATTRIBUTE = "visual_attribute"
    TEXT_OCR = "text_ocr"
    SPEECH = "speech"
    MUSIC = "music"
    ENVIRONMENTAL_SOUND = "environmental_sound"
    EVENT = "event"
    CONTEXT = "context"
    OTHER = "other"


class ObservationType(str, Enum):
    DIRECT_OBSERVATION = "direct_observation"   # directly detected / extracted
    INTERPRETATION = "interpretation"           # model's explanation of observations
    INFERENCE = "inference"                     # conclusion combining multiple items


class RelationshipType(str, Enum):
    AGREEMENT = "agreement"
    COMPLEMENTARY = "complementary"
    POTENTIAL_CONTRADICTION = "potential_contradiction"
    UNRELATED = "unrelated"
    INSUFFICIENT_EVIDENCE = "insufficient_evidence"
    DUPLICATE = "duplicate"
    OVERLAP = "overlap"


class EvidenceQualityStatus(str, Enum):
    COMPLETE = "complete"
    PARTIALLY_COMPLETE = "partially_complete"
    INSUFFICIENT_EVIDENCE = "insufficient_evidence"
    PROCESSING_FAILED = "processing_failed"
    REQUIRES_REVIEW = "requires_review"


# ---------------------------------------------------------------------------
# EvidenceSource — every item must identify where it came from
# ---------------------------------------------------------------------------


class EvidenceSource(BaseModel):
    """Provenance record for a single evidence item.

    Only fields applicable to the source are populated.
    """

    media_id: str
    collection_id: str
    media_type: str                          # image | video | audio
    modality: SourceModality

    # Image / carousel
    image_index: Optional[int] = None        # sequence_index in carousel

    # Video
    video_start_seconds: Optional[float] = None
    video_end_seconds: Optional[float] = None
    frame_index: Optional[int] = None

    # Audio
    audio_start_seconds: Optional[float] = None
    audio_end_seconds: Optional[float] = None

    # Provider provenance
    provider: str = ""
    model_id: str = ""
    processing_job_id: Optional[str] = None


# ---------------------------------------------------------------------------
# EvidenceItem — atomic unit of evidence
# ---------------------------------------------------------------------------


class EvidenceItem(BaseModel):
    """A single atomic piece of evidence with full provenance.

    observation_type distinguishes:
      direct_observation — directly detected from the media
      interpretation     — model's explanation of what was observed
      inference          — conclusion combining multiple evidence items

    Never store an inference as a direct_observation.
    """

    evidence_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    category: EvidenceCategory
    observation_type: ObservationType

    # The actual observation — text or structured value
    value: str                               # primary human-readable text
    structured_value: Optional[Dict[str, Any]] = None  # optional structured form

    source: EvidenceSource

    # Confidence — only set when the provider supplies it
    confidence: Optional[str] = None         # "high" | "medium" | "low" | None

    # Uncertainty
    uncertainty_note: Optional[str] = None   # free-text explanation of uncertainty

    # For interpretations and inferences: which evidence_ids support this
    supporting_evidence_ids: List[str] = []

    # Processing metadata
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    raw_provider_value: Optional[str] = None  # original provider text, preserved


# ---------------------------------------------------------------------------
# Cross-modal relationship
# ---------------------------------------------------------------------------


class CrossModalRelationship(BaseModel):
    """A relationship between evidence items from different modalities."""

    relationship_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    relationship_type: RelationshipType
    evidence_ids: List[str]                  # IDs of the related EvidenceItems
    description: str
    confidence: Optional[str] = None
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


# ---------------------------------------------------------------------------
# Contradiction record
# ---------------------------------------------------------------------------


class EvidenceConflict(BaseModel):
    """A potential contradiction between evidence items.

    A difference between modalities is not automatically a contradiction.
    This record preserves both sides without choosing a winner.
    """

    conflict_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    conflicting_evidence_ids: List[str]
    description: str
    source_references: List[str]             # human-readable source descriptions
    confidence: Optional[str] = None
    explanation: str
    resolution_status: str = "unresolved"    # unresolved | acknowledged | resolved
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


# ---------------------------------------------------------------------------
# Evidence quality dimensions
# ---------------------------------------------------------------------------


class EvidenceQualityDimensions(BaseModel):
    """Qualitative assessment of evidence completeness.

    Prefer explainable status labels over arbitrary numerical scores.
    """

    source_availability: str                 # ok | partial | missing
    observation_completeness: str            # ok | partial | missing
    timestamp_validity: str                  # ok | partial | missing | not_applicable
    provenance_completeness: str             # ok | partial | missing
    cross_modal_agreement: str               # agreement | complementary | conflict | not_applicable
    has_duplicates: bool
    has_unresolved_contradictions: bool
    has_processing_warnings: bool
    missing_modalities: List[str]            # e.g. ["audio", "ocr"]
    overall_status: EvidenceQualityStatus


# ---------------------------------------------------------------------------
# Content summary — grounded, not promotional
# ---------------------------------------------------------------------------


class ContentSummary(BaseModel):
    """A grounded summary built from validated evidence.

    Every field is populated only from evidence in the package.
    Uncertain or unsupported details are placed in uncertain_details.
    No promotional language. No invented facts.
    """

    overall_description: str
    main_subjects: List[str] = []            # directly observed subjects
    main_activities: List[str] = []          # directly observed activities
    environment_and_setting: Optional[str] = None
    important_visual_details: List[str] = []
    spoken_content: Optional[str] = None     # from transcription
    background_audio: Optional[str] = None   # from audio understanding
    visible_text: List[str] = []             # from OCR
    key_events_sequence: List[str] = []      # ordered events (video)
    uncertain_details: List[str] = []        # flagged as uncertain
    interpretation_notes: List[str] = []     # model interpretations, labelled
    evidence_basis: List[str] = []           # evidence_ids supporting this summary


# ---------------------------------------------------------------------------
# UnifiedMediaEvidence — top-level Phase 3 structure
# ---------------------------------------------------------------------------


class UnifiedMediaEvidence(BaseModel):
    """Complete, validated evidence package for one media collection.

    This is the output of the Phase 3 evidence pipeline and the input
    to the Phase 4 caption generator.

    The caption generator must only use information present in this
    structure and must not invent details not supported by the evidence.

    schema_version allows downstream consumers to detect breaking changes.
    """

    # Identity
    package_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    schema_version: str = SCHEMA_VERSION
    collection_id: str
    collection_type: str                     # single | carousel | video | audio

    # Asset references (ordered by sequence_index)
    asset_ids: List[str] = []

    # All evidence items (ordered: image → video → audio → fusion)
    evidence_items: List[EvidenceItem] = []

    # Modality-specific groupings (convenience views, not duplicates)
    image_evidence_ids: List[str] = []       # evidence_ids for image items
    carousel_sequence: List[str] = []        # evidence_ids in carousel order
    video_evidence_ids: List[str] = []
    audio_evidence_ids: List[str] = []
    transcription_evidence_ids: List[str] = []
    ocr_evidence_ids: List[str] = []

    # Cross-modal relationships
    cross_modal_relationships: List[CrossModalRelationship] = []

    # Contradictions
    conflicts: List[EvidenceConflict] = []

    # Quality
    quality: Optional[EvidenceQualityDimensions] = None

    # Content summary
    content_summary: Optional[ContentSummary] = None

    # Processing metadata
    processing_status: str = "pending"       # pending | partial | complete | failed
    processed_at: Optional[datetime] = None
    warnings: List[str] = []
    errors: List[str] = []

    # Provenance
    providers_used: List[str] = []
    source_media_evidence: Optional[Dict[str, Any]] = None  # raw Phase 2 MediaEvidence

    # Versioning
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    updated_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
